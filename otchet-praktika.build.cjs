function p(text, o = {}) {
  return new Paragraph({
    alignment: o.align ?? AlignmentType.JUSTIFIED,
    indent: { firstLine: o.firstLine ?? IND, left: o.left ?? 0 },
    spacing: { line: o.line ?? LINE, before: o.before ?? 0, after: o.after ?? 0 },
    keepNext: !!o.keepNext,
    pageBreakBefore: !!o.pageBreakBefore,
    children: [new TextRun({ text, bold: !!o.bold, italics: !!o.italic, size: o.size ?? SIZE, font: FONT })],
  });
}

function structural(text) {
  return new Paragraph({
    heading: docx.HeadingLevel.HEADING_1,
    alignment: AlignmentType.CENTER,
    spacing: { line: LINE, before: 0, after: 240 },
    pageBreakBefore: true,
    keepNext: true,
    children: [new TextRun({ text, bold: true, size: SIZE, font: FONT })],
  });
}

function h1(text) {
  return new Paragraph({
    heading: docx.HeadingLevel.HEADING_1,
    alignment: AlignmentType.LEFT,
    indent: { firstLine: IND },
    spacing: { line: LINE, before: 240, after: 120 },
    keepNext: true,
    children: [new TextRun({ text, bold: true, size: SIZE, font: FONT })],
  });
}

function h2(text, o = {}) {
  return new Paragraph({
    heading: docx.HeadingLevel.HEADING_2,
    alignment: AlignmentType.LEFT,
    indent: { firstLine: o.firstLine ?? IND },
    spacing: { line: LINE, before: 240, after: 120 },
    keepNext: true,
    children: [new TextRun({ text, bold: true, size: SIZE, font: FONT })],
  });
}

function item(text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { firstLine: IND },
    spacing: { line: LINE, after: 0 },
    children: [new TextRun({ text, size: SIZE, font: FONT })],
  });
}

function figure(file, width, height, caption) {
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { line: LINE, before: 120, after: 120 },
      keepNext: true,
      children: [new ImageRun({ type: "png", data: asset(file), transformation: { width, height } })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { line: LINE, after: 240 },
      children: [new TextRun({ text: caption, size: SIZE, font: FONT })],
    }),
  ];
}

const B = { style: BorderStyle.SINGLE, size: 6, color: "000000" };
const BORDERS = { top: B, bottom: B, left: B, right: B, insideHorizontal: B, insideVertical: B };

function tableCaption(text) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    spacing: { line: LINE, before: 240, after: 120 },
    keepNext: true,
    children: [new TextRun({ text, size: SIZE, font: FONT })],
  });
}

function cell(text, opts = {}) {
  return new TableCell({
    width: { size: opts.width, type: WidthType.PERCENTAGE },
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    borders: opts.borders,
    children: [
      new Paragraph({
        alignment: opts.align ?? AlignmentType.LEFT,
        spacing: { line: 240, before: 0, after: 0 },
        indent: { firstLine: 0 },
        children: [new TextRun({ text: String(text), bold: !!opts.bold, size: 24, font: FONT })],
      }),
    ],
  });
}

function table(rows, widths, aligns = []) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: BORDERS,
    rows: rows.map((r, ri) =>
      new TableRow({
        tableHeader: ri === 0,
        children: r.map((c, ci) =>
          cell(c, {
            width: widths[ci],
            bold: ri === 0,
            align: ri === 0 ? AlignmentType.CENTER : (aligns[ci] ?? AlignmentType.LEFT),
            borders: ri === 0
              ? { top: B, left: B, right: B, bottom: { style: BorderStyle.DOUBLE, size: 6, color: "000000" } }
              : undefined,
          }),
        ),
      }),
    ),
  });
}

function titleLine(text, o = {}) {
  return new Paragraph({
    alignment: o.align ?? AlignmentType.CENTER,
    spacing: { line: 240, before: o.before ?? 0, after: o.after ?? 0 },
    children: [new TextRun({ text, size: o.size ?? SIZE, font: FONT, bold: !!o.bold })],
  });
}

function sigLine(left, sign, right) {
  return new Paragraph({
    spacing: { line: 240, before: 240, after: 0 },
    tabStops: [
      { type: TabStopType.LEFT, position: 5100 },
      { type: TabStopType.LEFT, position: 7300 },
    ],
    children: [new TextRun({ text: `${left}\t${sign}\t${right}`, size: SIZE, font: FONT })],
  });
}

function sigNote(left, sign, right) {
  return new Paragraph({
    spacing: { line: 240, before: 0, after: 0 },
    tabStops: [
      { type: TabStopType.LEFT, position: 5100 },
      { type: TabStopType.LEFT, position: 7300 },
    ],
    children: [new TextRun({ text: `${left}\t${sign}\t${right}`, size: 20, font: FONT })],
  });
}

